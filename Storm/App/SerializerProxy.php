<?php

declare(strict_types=1);

namespace Vanqard\Storm\App;

use Closure;
use Vanqard\Storm\Exceptions\DisallowedClassException;
use Vanqard\Storm\Exceptions\InvalidSerializerInstanceException;
use Vanqard\Storm\Interfaces\SerializerInterface;
use Zumba\JsonSerializer\Exception\JsonSerializerException;
use Zumba\JsonSerializer\JsonSerializer;

/**
 * Adapts any object exposing serialize()/unserialize() to SerializerInterface.
 * Defaults to zumba/json-serializer, which embeds class names ('@type') so
 * objects rehydrate into their original classes.
 *
 * Deserialization is restricted to an allow-list of class names, which is
 * empty (nothing allowed) by default. The list is applied through the
 * serializer's setAllowedClasses() method; a custom serializer without that
 * method must enforce its own restrictions. Generate the list with
 * `vendor/bin/storm-allowlist`.
 */
class SerializerProxy implements SerializerInterface
{
    private const string TYPE_KEY = '@type';

    private Closure $serializeFn;

    private Closure $unserializeFn;

    /**
     * @var list<string>|null null means unrestricted
     */
    private ?array $allowedClasses;

    /**
     * @param list<string>|null $allowedClasses Classes that may be rehydrated. The
     *     default [] allows none; null removes the restriction entirely (unsafe).
     */
    public function __construct(mixed $serializer = null, ?array $allowedClasses = [])
    {
        $serializer ??= new JsonSerializer();

        $serialize = [$serializer, 'serialize'];
        if (!is_object($serializer) || !is_callable($serialize)) {
            throw new InvalidSerializerInstanceException('Serializer must provide a serialize function');
        }

        $unserialize = [$serializer, 'unserialize'];
        if (!is_callable($unserialize)) {
            throw new InvalidSerializerInstanceException('Serializer must provide an unserialize function');
        }

        if ($allowedClasses !== null) {
            $allowedClasses = self::validateClassList($allowedClasses, 'allowedClasses');
        }

        $setAllowedClasses = [$serializer, 'setAllowedClasses'];
        if (is_callable($setAllowedClasses)) {
            $setAllowedClasses($allowedClasses);
        }

        $this->serializeFn = Closure::fromCallable($serialize);
        $this->unserializeFn = Closure::fromCallable($unserialize);
        $this->allowedClasses = $allowedClasses;
    }

    /**
     * Creates a proxy restricted to the classes listed in a file generated by
     * `vendor/bin/storm-allowlist` (a PHP file returning a list of class names).
     *
     * @throws InvalidSerializerInstanceException when the file is missing or malformed
     */
    public static function fromAllowListFile(string $path): self
    {
        return new self(null, self::loadAllowListFile($path));
    }

    /**
     * Creates a proxy that rehydrates any class named in the data. Only use this
     * when every serialized value is written by your own application and the
     * storage can never be modified by anyone else.
     */
    public static function unrestricted(mixed $serializer = null): self
    {
        return new self($serializer, null);
    }

    /**
     * @return list<string>
     * @throws InvalidSerializerInstanceException
     */
    public static function loadAllowListFile(string $path): array
    {
        if (!is_file($path) || !is_readable($path)) {
            throw new InvalidSerializerInstanceException(
                sprintf("The allow-list file '%s' does not exist or is not readable", $path)
            );
        }

        $classes = (static fn (string $file): mixed => require $file)($path);

        if (!is_array($classes)) {
            throw new InvalidSerializerInstanceException(
                sprintf("The allow-list file '%s' must return an array of class names", $path)
            );
        }

        return self::validateClassList($classes, $path);
    }

    /**
     * @return list<string>|null
     */
    public function getAllowedClasses(): ?array
    {
        return $this->allowedClasses;
    }

    /**
     * @throws DisallowedClassException when the value contains an object whose
     *     class could not be rehydrated under the allow-list
     */
    public function serialize(mixed $value): string
    {
        $serialized = ($this->serializeFn)($value);

        if (!is_string($serialized)) {
            throw new InvalidSerializerInstanceException(
                sprintf("The serializer returned '%s' instead of a string", get_debug_type($serialized))
            );
        }

        if ($this->allowedClasses !== null) {
            $data = json_decode($serialized, true);
            if (is_array($data)) {
                $this->assertTypesAllowed($data);
            }
        }

        return $serialized;
    }

    /**
     * @throws DisallowedClassException when the data names a class that is not allowed
     */
    public function unserialize(mixed $value): mixed
    {
        try {
            return ($this->unserializeFn)($value);
        } catch (JsonSerializerException $e) {
            if (preg_match('/^Class (\S+) is not allowed for deserialization/', $e->getMessage(), $m) === 1) {
                throw DisallowedClassException::forClass($m[1], $e);
            }

            throw $e;
        }
    }

    /**
     * @param array<mixed> $data
     * @throws DisallowedClassException
     */
    private function assertTypesAllowed(array $data): void
    {
        $type = $data[self::TYPE_KEY] ?? null;

        // '@0', '@1', ... are back-references to objects already in the payload
        if (is_string($type) && !str_starts_with($type, '@') && !in_array($type, (array) $this->allowedClasses, true)) {
            throw DisallowedClassException::forClass($type);
        }

        foreach ($data as $child) {
            if (is_array($child)) {
                $this->assertTypesAllowed($child);
            }
        }
    }

    /**
     * @param array<mixed> $classes
     * @return list<string>
     * @throws InvalidSerializerInstanceException
     */
    private static function validateClassList(array $classes, string $source): array
    {
        $list = [];
        foreach ($classes as $class) {
            if (!is_string($class) || $class === '') {
                throw new InvalidSerializerInstanceException(
                    sprintf("The allow-list from '%s' must contain only non-empty class-name strings", $source)
                );
            }

            $list[] = ltrim($class, '\\');
        }

        return array_values(array_unique($list));
    }
}
