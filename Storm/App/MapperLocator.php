<?php

declare(strict_types=1);

namespace Vanqard\Storm\App;

use Aura\Sql\ExtendedPdo;
use ReflectionClass;
use Vanqard\Storm\Exceptions\InvalidMapperClassDeclaration;
use Vanqard\Storm\Exceptions\InvalidParameterException;
use Vanqard\Storm\Interfaces\SerializerInterface;
use Vanqard\Storm\Metadata\EntityMetadataFactory;
use Vanqard\Storm\Types\TypeRegistry;

/**
 * Creates and caches one configured mapper per entity class.
 */
class MapperLocator
{
    protected ExtendedPdo $connection;

    protected SerializerInterface $serializer;

    protected EntityMetadataFactory $metadataFactory;

    protected TypeRegistry $typeRegistry;

    /**
     * @var array<class-string, AbstractMapper<*>>
     */
    private array $mappers = [];

    /**
     * @param list<string>|string|null $allowedClasses Classes that `object` columns may
     *     rehydrate: a list of class names, or the path to a file generated by
     *     `vendor/bin/storm-allowlist`. When omitted (and no serializer is given),
     *     no classes may be rehydrated. Use SerializerProxy::unrestricted() as the
     *     serializer to lift the restriction.
     * @throws InvalidParameterException when both a serializer and allowedClasses are given
     */
    public function __construct(
        ExtendedPdo $connection,
        ?SerializerInterface $serializer = null,
        ?EntityMetadataFactory $metadataFactory = null,
        ?TypeRegistry $typeRegistry = null,
        array|string|null $allowedClasses = null,
    ) {
        if ($serializer !== null && $allowedClasses !== null) {
            throw new InvalidParameterException(
                'Pass either a serializer or allowedClasses, not both; configure the allow-list on your SerializerProxy instead'
            );
        }

        $this->connection = $connection;
        $this->serializer = $serializer ?? match (true) {
            is_string($allowedClasses) => SerializerProxy::fromAllowListFile($allowedClasses),
            default => new SerializerProxy(null, $allowedClasses ?? []),
        };
        $this->metadataFactory = $metadataFactory ?? new EntityMetadataFactory();
        $this->typeRegistry = $typeRegistry ?? new TypeRegistry($this->serializer);
    }

    public function getConnection(): ExtendedPdo
    {
        return $this->connection;
    }

    public function getSerializer(): SerializerInterface
    {
        return $this->serializer;
    }

    /**
     * Replaces the serializer used by mappers created after this call. Note
     * that the 'object' typecast keeps the serializer it was constructed with;
     * pass a TypeRegistry to the constructor to change that.
     */
    public function setSerializer(SerializerInterface $serializer): static
    {
        $this->serializer = $serializer;
        $this->mappers = [];
        return $this;
    }

    public function getMetadataFactory(): EntityMetadataFactory
    {
        return $this->metadataFactory;
    }

    public function getTypeRegistry(): TypeRegistry
    {
        return $this->typeRegistry;
    }

    /**
     * @template T of AbstractEntity
     * @param class-string<T> $entityClass
     * @return AbstractMapper<T>
     * @throws InvalidMapperClassDeclaration
     */
    public function mapper(string $entityClass): AbstractMapper
    {
        if (isset($this->mappers[$entityClass])) {
            /** @var AbstractMapper<T> */
            return $this->mappers[$entityClass];
        }

        $metadata = $this->metadataFactory->getMetadata($entityClass);
        $mapperClass = $metadata->getMapper() ?: GenericMapper::class;

        if (!class_exists($mapperClass) || !is_subclass_of($mapperClass, AbstractMapper::class)) {
            throw new InvalidMapperClassDeclaration(
                sprintf(
                    "The entity class '%s' declares '%s' as its mapper, which is not a subclass of %s",
                    $entityClass,
                    $mapperClass,
                    AbstractMapper::class
                )
            );
        }

        $constructor = (new ReflectionClass($mapperClass))->getConstructor();
        if ($constructor !== null && $constructor->getNumberOfRequiredParameters() > 0) {
            throw new InvalidMapperClassDeclaration(
                sprintf(
                    "The mapper '%s' must be constructable without arguments; dependencies are injected by the MapperLocator",
                    $mapperClass
                )
            );
        }

        /** @var AbstractMapper<T> $mapper */
        $mapper = new $mapperClass();
        $this->prepareMapper($mapper, $metadata->getTable(), $entityClass);

        return $this->mappers[$entityClass] = $mapper;
    }

    /**
     * @template T of AbstractEntity
     * @param AbstractMapper<T> $mapper
     * @param class-string<T> $entityClassName
     * @return AbstractMapper<T>
     */
    protected function prepareMapper(
        AbstractMapper $mapper,
        string $tableName,
        string $entityClassName
    ): AbstractMapper {
        return $mapper->setConnection($this->connection)
            ->setTableName($tableName)
            ->setSerializer($this->serializer)
            ->setMetadataFactory($this->metadataFactory)
            ->setTypeRegistry($this->typeRegistry)
            ->setEntityClassName($entityClassName);
    }
}
