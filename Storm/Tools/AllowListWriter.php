<?php

declare(strict_types=1);

namespace Vanqard\Storm\Tools;

use Vanqard\Storm\Exceptions\InvalidParameterException;

/**
 * Writes a deserialization allow-list as a PHP file that returns an array of
 * class names, suitable for `require` or SerializerProxy::fromAllowListFile().
 */
final class AllowListWriter
{
    /**
     * @param list<string> $classes
     * @param list<string> $sourcePaths Recorded in the file header for reference
     * @throws InvalidParameterException when the target directory is missing or the write fails
     */
    public function write(string $path, array $classes, array $sourcePaths = []): void
    {
        $directory = dirname($path);
        if (!is_dir($directory)) {
            throw new InvalidParameterException(sprintf("The directory '%s' does not exist", $directory));
        }

        $temp = tempnam($directory, '.storm-allowlist-');
        if ($temp === false || file_put_contents($temp, $this->render($classes, $sourcePaths)) === false) {
            throw new InvalidParameterException(sprintf("Unable to write to the directory '%s'", $directory));
        }

        chmod($temp, 0644);

        if (!rename($temp, $path)) {
            @unlink($temp);
            throw new InvalidParameterException(sprintf("Unable to write the allow-list to '%s'", $path));
        }
    }

    /**
     * @param list<string> $classes
     * @param list<string> $sourcePaths
     */
    public function render(array $classes, array $sourcePaths = []): string
    {
        $classes = array_values(array_unique(array_map(
            static fn (string $c): string => ltrim($c, '\\'),
            $classes
        )));
        sort($classes, SORT_STRING);

        $lines = [
            '<?php',
            '',
            'declare(strict_types=1);',
            '',
            '// Classes that Storm may rehydrate from serialized `object` columns.',
            '// Generated by vendor/bin/storm-allowlist. Do not edit by hand; regenerate instead.',
        ];

        if ($sourcePaths !== []) {
            $lines[] = '// Scanned: ' . implode(', ', $sourcePaths);
        }

        $lines[] = '';
        $lines[] = 'return [';
        foreach ($classes as $class) {
            $lines[] = '    ' . var_export($class, true) . ',';
        }
        $lines[] = '];';

        return implode("\n", $lines) . "\n";
    }
}
